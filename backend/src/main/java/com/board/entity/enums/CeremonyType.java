package com.board.entity.enums;

/**
 * Types of Scrum ceremonies/events.
 */
public enum CeremonyType {

    /**
     * Sprint Planning - Define sprint goal and select stories.
     */
    PLANNING,

    /**
     * Daily Standup - Quick daily sync meeting.
     */
    DAILY,

    /**
     * Sprint Review - Demo completed work to stakeholders.
     */
    REVIEW,

    /**
     * Sprint Retrospective - Team reflection and improvement.
     */
    RETROSPECTIVE,

    /**
     * Backlog Refinement - Estimate and clarify upcoming stories.
     */
    REFINEMENT
}
