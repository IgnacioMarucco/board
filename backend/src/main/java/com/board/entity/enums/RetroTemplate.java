package com.board.entity.enums;

/**
 * Template types for retrospective ceremonies.
 */
public enum RetroTemplate {

    /**
     * Start/Stop/Continue format.
     */
    START_STOP_CONTINUE,

    /**
     * Mad/Sad/Glad format.
     */
    MAD_SAD_GLAD,

    /**
     * 4Ls format: Liked, Learned, Lacked, Longed for.
     */
    FOUR_LS
}
