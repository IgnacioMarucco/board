package com.board.entity.enums;

/**
 * Enum for entity types that can have attachments.
 */
public enum AttachmentType {
    /**
     * Attachment for epic.
     */
    EPIC,

    /**
     * Attachment for story.
     */
    STORY,

    /**
     * Attachment for task.
     */
    TASK,

    /**
     * Attachment for comment.
     */
    COMMENT,

    /**
     * Attachment for ceremony (e.g., retrospective documents).
     */
    CEREMONY
}
