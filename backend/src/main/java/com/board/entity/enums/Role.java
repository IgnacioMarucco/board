package com.board.entity.enums;

/**
 * Roles available for project members following Scrum methodology.
 */
public enum Role {

    /**
     * Product Owner - Maximizes product value, manages backlog, accepts stories.
     */
    PRODUCT_OWNER,

    /**
     * Scrum Master - Facilitates process, removes impediments, manages sprints.
     */
    SCRUM_MASTER,

    /**
     * Developer - Builds the product increment, creates and manages tasks.
     */
    DEVELOPER
}
